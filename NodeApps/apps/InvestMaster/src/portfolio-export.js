export function buildPortfolioExport(lessons, notes, dateLabel) {
  const drafts = lessons
    .filter(lesson => lesson.unit === '毕业研究')
    .map(lesson => ({ lesson, note: notes.find(note => note.id === lesson.id) }))
    .filter(({ note }) => typeof note?.body === 'string' && note.body.trim());
  if (!drafts.length) return null;

  const dimensions = ['来源与公开时点', '三表、现金流及估值勾稽', '情景、反证与敏感性', '债券条款、到期及回收顺位', '客户现金义务与组合适配', '利益冲突、费用与表达'];
  const reviewSheet = [
    '## 独立审读记录（由审读者填写）', '',
    '作者：____　审读者：____　研究截止日：____　审读日期：____　资料版本：____',
    '审读者先独立复算，再阅读作者结论；看不到原始文件、公式或合同的项目记为「未核实」。', '',
    '### 作品与底稿索引', '',
    '| 必交作品 | 原始资料和公开日期 | 公式文件及版本 | 审读结果／返工项 |',
    '| --- | --- | --- | --- |',
    ...['股票 A（行业：____）', '股票 B（不同收入与资本投入逻辑的行业：____）', '普通债券合同、价格与信用报告', '客户 IPS 与联合压力现金表', '反方答辩、v1→v2 与新披露复盘'].map(label => `| ${label} | 待填 | 待填 | 待审 |`), '',
    '### 六维评分', '',
    '| 维度 | 0–4 分 | 对应证据、页码或公式 | 需要修订之处 |',
    '| --- | ---: | --- | --- |',
    ...dimensions.map(label => `| ${label} | 待审 | 待填 | 待填 |`), '',
    '评分锚点：0＝缺失或方法不成立；1＝能复述但无法从证据重建；2＝基本方法正确但重要缺口未解释；3＝可独立重建且主要约束一致，剩余限制明确；4＝在未见资料上迁移、经反方复算，并能正确处理可能改变结论的新证据。各维具体证据按综合研究课的量表检查；原判断被支持时可保留结论并说明证据，无须为得分制造错误或强行改变观点。', '',
    '### 不可由高分抵消的返工条件', '',
    '- [ ] 两家不同行业企业各有独立股票报告；没有把后来的资料放回事前。',
    '- [ ] 另一人能从输入重算 CFO、FCFF、企业价值到每股价值；重大未解释差额未被掩盖。',
    '- [ ] 债券发行实体、保证、到期及生效回收顺位来自文件；无法确认处明确写「未核实」，没有据此宣称安全。',
    '- [ ] 悲观情景会改变模型和仓位；客户确定付款有独立、可按时动用的资金来源。',
    '- [ ] 有独立审读者复算；没有仅凭选择题、自评或事后盈利判为通过。',
    '- [ ] 作者列出最强反方意见、修订触发条件、费用、利益冲突与未知事项。', '',
    '### 未见题、答辩与返工', '',
    '未见资料或题目：____　起止时间：____　允许工具：____　参考答案是否事先可见：____',
    '独立复算的三个关键数字（来源→输入→公式→结果）：',
    '1. ____', '2. ____', '3. ____', '',
    '反方改变的一项假设：____',
    '作者如何重算估值、损失、客户付款与行动：____',
    '审读者发现的最重要错误或确认仍成立的关键推导：____',
    '作者 v2 修改或保留的公式、结论或行动、理由及对应文件：____',
    '新披露公开日期：____　v1 是否被支持／推翻／仍未知：____',
    '仍待取得的资料与再次审读日期：____', '',
    '### 本 APP 的学习验收', '',
    '首次审读：待审／返工／基础通过／优秀　六维分数：____／24',
    '返工后审读：待审／返工／基础通过／优秀　六维分数：____／24',
    '基础通过要求：必交作品齐全、上述关键检查全部满足、六维均至少 3 分、未见数量会计实作与反方答辩可复算。',
    '优秀要求：在基础通过之上至少 22／24 分，两份股票报告能够解释跨行业模型变化，并完成一次新披露后的可追溯复盘。',
    '这些分界是本课程的学习标准，须由独立审读者逐项给证据；不是大学学位标准、执业资格或收益保证。尚未取得新披露时复盘记为待完成，未审读草稿不得标为能力已验收。',
  ];

  return [
    '# Invest Master · 毕业作品草稿', '',
    `导出日期：${dateLabel}`, '',
    '以下是本机保存的学习草稿；请选择独立审读者核对原始资料、计算与反方意见。完整表格、模型和原始文件须另附，未保存文字不在本次导出中。', '',
    ...drafts.flatMap(({ lesson, note }) => [
      `## ${lesson.title}`, '',
      `课题 ID：${lesson.id}`,
      ...(note.updatedAt ? [`草稿保存时间：${note.updatedAt}`] : []),
      `课题要求：${lesson.practice}`, '', note.body.trim(), '',
    ]),
    ...reviewSheet,
  ].join('\n');
}
