const write = (type, id, meta, body) => {
  const directory = path.join(root, 'content', type);
  fs.mkdirSync(directory, { recursive: true });
  const lines = ['---', `id: ${id}`];
  for (const [key, value] of Object.entries(meta)) lines.push(`${key}: ${JSON.stringify(value)}`);
  fs.writeFileSync(path.join(directory, `${id}.md`), `${lines.join('\n')}\n---\n\n${body.trim()}\n`, 'utf8');
};

