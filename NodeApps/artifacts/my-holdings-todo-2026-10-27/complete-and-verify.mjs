import fs from "node:fs";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {validateResearch} from "../../apps/my_holdings/server/ai.js";
import {validateState} from "../../apps/my_holdings/server/index.js";
const dir="artifacts/my-holdings-todo-2026-10-27";
const before=JSON.parse(fs.readFileSync(dir+"/before.json","utf8"));
const hash=value=>crypto.createHash("sha256").update(JSON.stringify(value)).digest("hex");
const read=()=>JSON.parse(fs.readFileSync("apps/my_holdings/data/state.json","utf8"));
const jobId="b7fd022c-5b5e-41e7-8542-ef57306db06d";
const watchId="bcdb53f1-c038-4c1d-93f9-77489dddee7b";
const state=read();
const watch=state.watchlist.find(w=>w.id===watchId);
const report="research/my-holdings-research-clpt-2026-10-27.html";
const research=JSON.parse(fs.readFileSync("apps/my_holdings/data/reports/"+report.replace(/\.html$/,".json"),"utf8"));
validateResearch(research);
assert.equal(research.identity.symbol,"CLPT");
assert.equal(research.quote,undefined);
assert(research.details.length>5000);
assert(fs.statSync("apps/my_holdings/data/reports/"+report).size>10000);
const alreadyComplete=Boolean(watch.research?.details?.trim()&&watch.report);
const payload=alreadyComplete?{}:{report,research};
if(state.jobs.find(j=>j.id===jobId)?.status==="waiting"){
  fs.writeFileSync(dir+"/research-complete.json",JSON.stringify(payload,null,2));
  const r=await fetch("http://127.0.0.1:5889/my-holdings/api/jobs/"+jobId+"/complete",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(payload)});
  const response=await r.json();
  if(!r.ok)throw new Error(JSON.stringify(response));
}
const after=read();
validateState(after);
for(const [key,expected]of Object.entries(before.hashes)) assert.equal(hash(after[key]),expected,"Unrelated data changed: "+key);
assert.equal(hash(after.watchlist.filter(w=>!before.jobs.some(j=>j.watchId===w.id))),before.otherWatchlistHash);
for(const old of before.jobs)assert.equal(after.jobs.find(j=>j.id===old.id).status,"done");
const current=after.watchlist.find(w=>w.id===watchId);
assert.equal(current.price,9.14);
assert.equal(current.priceDate,"2026-10-23");
assert.equal(current.priceType,"close");
assert.equal(current.priceCurrency,"USD");
assert(current.priceFetchedAt&&current.priceSourceUrl&&current.researchedAt&&current.report&&current.research.details);
assert.equal(after.jobs.filter(j=>j.status==="waiting").length,0);
assert(!fs.readFileSync("apps/my_holdings/data/CODEX_TODO.md","utf8").includes("状态：等待 Codex"));
const result={completed:before.jobs.map(j=>({id:j.id,kind:j.kind,status:"done"})),waiting:0,revision:after.revision,quote:{symbol:"CLPT",price:current.price,date:current.priceDate,type:current.priceType,currency:current.priceCurrency,source:current.priceSource},report:current.report,summary:current.research.summary,unrelatedDataPreserved:true,existingResearchSkipped:alreadyComplete};
fs.writeFileSync(dir+"/completion-verification.json",JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
